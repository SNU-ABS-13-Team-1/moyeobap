-- 바둑: 계가 신청(제안 → 상대 수락)
--
-- 지금까지 계가 단계(status='scoring')로 들어가는 길은 두 번 연속 패스뿐이라,
-- 승패가 이미 뚜렷한 판에서도 서로 패스를 주고받아야 끝낼 수 있었습니다.
-- 대국 중에 계가를 신청하고 상대가 수락하면 바로 계가로 넘어가게 합니다.
--
-- 체스의 무승부 제안(chess_rooms.draw_offer_by)과 같은 구조입니다.
-- 신청자 id를 담아 두고, 수락되거나 거절되거나 누군가 수를 두면 비웁니다.
-- 계가를 실제로 확정하는 건 여전히 양쪽의 '계가 동의'(*_confirmed_score)라
-- 이 신청은 "계가 화면으로 함께 넘어가자"는 합의까지만 담당합니다.
-- ========================================================

ALTER TABLE public.baduk_rooms
    ADD COLUMN IF NOT EXISTS score_offer_by UUID REFERENCES auth.users(id) ON DELETE SET NULL;
